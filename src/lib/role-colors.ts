function keyFor(role: string): string {
  return role.trim().toLowerCase().replace(/\s+/g, " ");
}

export function colorForRole(role: string): string {
  const key = keyFor(role);
  return ROLE_COLORS[key] ?? FALLBACK[toneForRole(role)] ?? "#ffffff";
}

export function inkForColor(hex: string): string {
  const raw = hex.replace("#", "");
  const r = Number.parseInt(raw.slice(0, 2), 16);
  const g = Number.parseInt(raw.slice(2, 4), 16);
  const b = Number.parseInt(raw.slice(4, 6), 16);
  const y = (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255;
  return y > 0.62 ? "#1c1916" : "#f7f4ef";
}
